import { test, expect, type Page } from '@playwright/test';
const nav = (page: Page, name: string) => page.locator('.top-nav').getByRole('button', { name, exact: true }).click();
const sidebar = (page: Page) => page.locator('.collection-sidebar');
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => { localStorage.setItem('kinemaMockMusic','1'); localStorage.setItem('kinema.music.language','en'); });
  await page.goto('/');
});

test('music has the approved sidebar, independent views and sorting, and clean management', async ({ page }) => {
  await nav(page,'Music');
  await expect(sidebar(page)).toBeVisible();
  await expect(sidebar(page).getByRole('button', { name:'All music (3)',exact:true })).toBeVisible();
  await expect(page.locator('.music-page .music-collections')).toHaveCount(0);
  await expect(page.getByRole('button', { name:'Add collection',exact:true })).toHaveCount(0);
  await page.getByRole('button', { name:'Album',exact:true }).click();
  await expect(page.locator('.music-album-tile')).toHaveCount(2);
  await page.getByRole('button', { name:'Year',exact:true }).click();
  await expect(page.getByRole('button', { name:'Year',exact:true })).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('.music-library-group > h2')).toHaveText(['2026']);
  await expect(page.getByRole('searchbox')).toHaveCount(0);
  await page.getByRole('button', { name:'Search music',exact:true }).click();
  await page.getByRole('searchbox').fill('First');
  await expect(page.locator('.music-album-tile')).toHaveCount(1);
  await page.getByRole('button',{name:'Search music',exact:true}).click();
  await expect(page.getByRole('searchbox')).toHaveCount(0);
  await page.screenshot({path:'work/sidebar-music-desktop.png'});
  await sidebar(page).getByRole('button',{name:'Collapse collections',exact:true}).click();
  await expect(sidebar(page)).toHaveCount(0);
  await page.getByRole('button',{name:'Collections',exact:true}).click();
  await expect(sidebar(page)).toBeVisible();
  await sidebar(page).getByRole('button',{name:'Manage collections',exact:true}).click();
  await expect(page.locator('.music-folder-settings')).toBeVisible();
  await expect(page.getByRole('button',{name:'Add music folder',exact:true})).toBeVisible();
});

test('music collection creation stays in Settings and All music browsing remains usable', async ({ page }) => {
  await nav(page,'Music');
  await sidebar(page).getByRole('button',{name:'Manage collections',exact:true}).click();
  const manager=page.locator('.music-folder-settings');
  await manager.getByRole('button',{name:'Add collection',exact:true}).click();
  await manager.getByLabel('Collection name',{exact:true}).fill('Christmas');
  await manager.getByRole('button',{name:'Create',exact:true}).click();
  await nav(page,'Music');
  await expect(sidebar(page).getByRole('button',{name:'Christmas (0)',exact:true})).toBeVisible();
  await sidebar(page).getByRole('button',{name:'Music (3)',exact:true}).click();
  await expect(page.locator('.music-album-tile')).toHaveCount(1);
  await sidebar(page).getByRole('button',{name:'All music (3)',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Music',exact:true})).toBeVisible();
  await sidebar(page).getByRole('button',{name:'Manage collections',exact:true}).click();
  await expect(manager.getByRole('button',{name:'Add music folder',exact:true})).toBeEnabled();
});

test('movie and TV collections use poster sidebars, with settings and filters tucked away', async ({ page }) => {
  await nav(page,'Movies');
  await expect(sidebar(page).getByRole('button',{name:'All movies (1)',exact:true})).toBeVisible();
  await expect(page.getByRole('combobox',{name:'Movie collection',exact:true})).toHaveCount(0);
  await sidebar(page).getByRole('button',{name:'Manage collections',exact:true}).click();
  const manager=page.getByRole('region',{name:'Movie collections',exact:true});
  await manager.getByRole('button',{name:'Add collection',exact:true}).click();
  await manager.getByLabel('Collection name',{exact:true}).fill('Christmas movies');
  await manager.getByRole('button',{name:'Create collection',exact:true}).click();
  await page.evaluate(()=>localStorage.setItem('kinemaMockPick','C:/Christmas movies'));
  await manager.getByRole('button',{name:'Add folder',exact:true}).click();
  await expect(manager.getByRole('status')).toContainText(/Scan finished|Folder added/);
  await nav(page,'Movies');
  await sidebar(page).getByRole('button',{name:'Christmas movies (1)',exact:true}).click();
  await expect(page.locator('.search-grid .card-title')).toHaveText(['Example Film']);
  await expect(page.getByRole('heading',{name:'Christmas movies',exact:true})).toBeVisible();
  await page.getByRole('combobox',{name:'Sort movies by',exact:true}).selectOption('year');
  await page.getByRole('button',{name:'Filters',exact:true}).click();
  await expect(page.getByRole('menu',{name:'Library filters',exact:true})).toBeVisible();
  await page.getByRole('heading',{name:'Christmas movies',exact:true}).click();
  await expect(page.getByRole('menu',{name:'Library filters',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Filters',exact:true}).click();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('menu',{name:'Library filters',exact:true})).toHaveCount(0);
  await expect(page.getByRole('heading',{name:'Christmas movies',exact:true})).toBeVisible();
  await page.screenshot({path:'work/sidebar-movies-desktop.png'});
  await sidebar(page).getByRole('button',{name:'Manage collections',exact:true}).click();
  await expect(page.getByRole('combobox',{name:'Movie collection',exact:true}).locator('option:checked')).toHaveText('Christmas movies');
  await nav(page,'Movies');

  await nav(page,'TV shows');
  await expect(sidebar(page).getByRole('button',{name:'All TV (2)',exact:true})).toBeVisible();
  await expect(page.locator('.search-grid .card')).toHaveCount(2);
  const posters=page.locator('.search-grid .card');
  await posters.first().focus(); await page.keyboard.press('ArrowLeft');
  await expect(sidebar(page).getByRole('button',{name:'TV shows (2)',exact:true})).toHaveClass(/focused/);
  await page.keyboard.press('ArrowRight'); await expect(posters.first()).toHaveClass(/focused/);
  await page.screenshot({path:'work/sidebar-tv-desktop.png'});
});

test('controller moves between artwork and sidebar, while Handheld uses a dismissible drawer', async ({ page }) => {
  await page.evaluate(()=>localStorage.setItem('kinemaMockMusicGrid','1'));
  await nav(page,'Music');
  const tiles=page.locator('.music-album-grid > button');
  await expect(tiles).toHaveCount(20);
  await tiles.first().focus(); await page.keyboard.press('ArrowLeft');
  await expect(sidebar(page).getByRole('button',{name:'Music (20)',exact:true})).toHaveClass(/focused/);
  await page.keyboard.press('ArrowRight');
  await expect(tiles.first()).toHaveClass(/focused/);
  await nav(page,'Settings');
  await page.getByRole('navigation',{name:'Settings sections'}).getByRole('button',{name:'Playback',exact:true}).click();
  await page.getByRole('radiogroup',{name:'Where Kinema is used',exact:true}).getByRole('button',{name:'Handheld',exact:true}).click();
  await page.setViewportSize({width:854,height:480});
  await nav(page,'Music');
  await expect(sidebar(page)).toHaveCount(0);
  const toggle=page.getByRole('button',{name:'Collections',exact:true});
  await toggle.click();
  await expect(sidebar(page)).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(sidebar(page)).toHaveCount(0);
  await toggle.click();
  await sidebar(page).getByRole('button',{name:'All music (20)',exact:true}).click();
  await expect(sidebar(page)).toHaveCount(0);
  await expect(tiles).toHaveCount(20);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'work/sidebar-handheld.png'});
  await toggle.click();
  await page.locator('.library-sidebar-backdrop').click({position:{x:800,y:300}});
  await expect(sidebar(page)).toHaveCount(0);
});
